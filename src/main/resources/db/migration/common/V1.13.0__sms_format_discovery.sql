-- =====================================================================================
-- Budget Insights - SMS format discovery (Phases 1 and 2).
--
-- WHAT THIS IS
--   A bank SMS that no parser template can read is lost today. These tables let the service learn
--   new formats from real handsets WITHOUT receiving any message:
--     Phase 1  bi_unmatched_sms_stat      how many unreadable money SMS each sender produced per
--                                         day, per hashed device. Counts only.
--     Phase 2  bi_sms_vocabulary          the shared list of bank words a handset may name by id.
--              bi_sms_format_candidate    one row per sender + message shape ("skeleton").
--              bi_sms_format_sample       one row per user per shape: an HMAC of the user (keyed by BI_FORMAT_USER_HASH_KEY),
--                                         never the user id. Expires after 90 days.
--   A shape is shown to a Super Admin only once 5 or more different users have sent it.
--
-- WHAT IS NEVER STORED
--   SMS text, amounts, account or card numbers, dates, names or merchants. A skeleton is
--   vocabulary ids + typed placeholders; the grammar is enforced by SkeletonGrammar before a row
--   is written, and token_key / display_text can only hold vocabulary words, placeholders, format
--   letters and punctuation.
--
-- FLAGS
--   Both phases ship OFF (moipay.budget-insights.format-discovery.enabled / samples-enabled).
--   Creating the tables changes nothing until an environment turns them on.
--
-- VOCABULARY
--   Ids are permanent: phones cache them. A word is retired (is_active = false, retired_in_version
--   = the new version), never renumbered or reused. Retiring bumps the version, so phones fetch
--   the list again and stop sending the word.
--   Version 1 = the wording of the seeded templates + common banking words + joining words + bank
--   names. No personal names, merchants or places; no OTP / PIN / password / code wording
--   (SmsVocabularySeedTest runs OtpGuard over every word).
-- =====================================================================================

CREATE TABLE IF NOT EXISTS budget_insights.bi_unmatched_sms_stat (
    id           uuid         PRIMARY KEY,
    stat_day     date         NOT NULL,
    sender_id    varchar(16)  NOT NULL,
    device_hash  varchar(64)  NOT NULL,
    msg_count    integer      NOT NULL,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ux_bi_unmatched_stat_day_sender_device UNIQUE (stat_day, sender_id, device_hash),
    CONSTRAINT ck_bi_unmatched_stat_count CHECK (msg_count BETWEEN 0 AND 500)
);
CREATE INDEX IF NOT EXISTS ix_bi_unmatched_stat_day
    ON budget_insights.bi_unmatched_sms_stat (stat_day);

CREATE TABLE IF NOT EXISTS budget_insights.bi_sms_vocabulary (
    id                integer      PRIMARY KEY,
    word              varchar(24)  NOT NULL,
    source            varchar(12)  NOT NULL,
    is_active         boolean      NOT NULL DEFAULT true,
    added_in_version  integer      NOT NULL,
    retired_in_version integer,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ux_bi_sms_vocabulary_word UNIQUE (word),
    CONSTRAINT ck_bi_sms_vocabulary_word CHECK (word ~ '^[A-Z]{1,24}$'),
    CONSTRAINT ck_bi_sms_vocabulary_source CHECK (source IN ('FUNCTION', 'BANKING', 'BANK', 'TEMPLATE')),
    CONSTRAINT ck_bi_sms_vocabulary_version CHECK (added_in_version >= 1),
    CONSTRAINT ck_bi_sms_vocabulary_retired CHECK (
        (is_active AND retired_in_version IS NULL)
        OR (NOT is_active AND retired_in_version > added_in_version))
);

CREATE TABLE IF NOT EXISTS budget_insights.bi_sms_format_candidate (
    id              uuid           PRIMARY KEY,
    sender_id       varchar(16)    NOT NULL,
    format_hash     varchar(64)    NOT NULL,
    token_key       varchar(3000)  NOT NULL,
    display_text    varchar(3000)  NOT NULL,
    token_count     integer        NOT NULL,
    distinct_users  integer        NOT NULL DEFAULT 0,
    sample_count    integer        NOT NULL DEFAULT 0,
    first_seen_at   timestamptz    NOT NULL,
    last_seen_at    timestamptz    NOT NULL,
    status          varchar(10)    NOT NULL DEFAULT 'OPEN',
    reject_reason   varchar(20),
    template_id     uuid,
    decided_by      uuid,
    decided_at      timestamptz,
    CONSTRAINT ux_bi_sms_candidate_sender_hash UNIQUE (sender_id, format_hash),
    CONSTRAINT ck_bi_sms_candidate_status CHECK (status IN ('OPEN', 'RESOLVED', 'REJECTED'))
);
CREATE INDEX IF NOT EXISTS ix_bi_sms_candidate_status_users
    ON budget_insights.bi_sms_format_candidate (status, distinct_users DESC);

CREATE TABLE IF NOT EXISTS budget_insights.bi_sms_format_sample (
    id                  uuid         PRIMARY KEY,
    candidate_id        uuid         NOT NULL
        REFERENCES budget_insights.bi_sms_format_candidate (id) ON DELETE CASCADE,
    user_hash           varchar(64)  NOT NULL,
    vocabulary_version  integer      NOT NULL,
    platform            varchar(8),
    received_at         timestamptz  NOT NULL,
    ttl_expires_at      timestamptz  NOT NULL,
    CONSTRAINT ux_bi_sms_sample_candidate_user UNIQUE (candidate_id, user_hash)
);
CREATE INDEX IF NOT EXISTS ix_bi_sms_sample_ttl  ON budget_insights.bi_sms_format_sample (ttl_expires_at);
CREATE INDEX IF NOT EXISTS ix_bi_sms_sample_user ON budget_insights.bi_sms_format_sample (user_hash);

